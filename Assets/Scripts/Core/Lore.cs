        public string Quote;
        /// <summary>Номер осколка летописи Строителей (1..7), 0 — обычная запись.</summary>
        public int Shard;
        /// <summary>Запись открывается сама, когда условие выполнено (знакомство, разведка узла силы).</summary>
        public Func<bool> Auto;
    }

    /// <summary>
    /// Архив (окно LoreWindow, клавиша Y) — лор галактики, который игрок собирает по ходу партии.
    ///
    /// Сквозная тайна — «Великое Молчание»: Строители (они же Предтечи; сами себя звали Звучащими) шестьдесят тысяч лет
    /// назад связали галактику вратами и песней, пока из-за края не пришёл Слушающий — то, что находит цивилизации
    /// по «звуку» (гиперпрыжкам, сигналам, мыслям). Строители замолчали: погасили звёзды, закрыли врата, оставили
