        private static string KeyOfOwner(int owner) => FactionRegistry.KeyOf(FactionTraits.FactionOf(owner));

        public static string PlayerFactionKey => KeyOfOwner(0);

        /// <summary>Народ известен: это наша фракция или мы знакомы с империей этой фракции.</summary>
        public static bool FactionKnown(string key)
        {
            if (string.IsNullOrEmpty(key)) return false;
            if (PlayerFactionKey == key) return true;
            foreach (var ai in AIEmpireManager.All)
                if (ai != null && Contacts.PlayerMet(ai.OwnerId) && KeyOfOwner(ai.OwnerId) == key) return true;
            return false;
        }

        private static bool LandmarkKnown(int type)
        {
            foreach (var s in Landmarks.All) if (s.Landmark == type && Vision.PlayerKnows(s.Id)) return true;
            return false;
        }

        public static string CategoryName(LoreCategory c) => c switch
