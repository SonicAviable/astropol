    ///
    /// Семь осколков летописи открываются строго по порядку (разведка особых мест — EventDatabase.Lore,
    /// а также «Ответ из глубины», ядро Предтеч и победа над левиафаном). Собран седьмой — через 2 месяца
    /// начинается финальная цепочка «Великое Молчание» с тремя исходами (записи раздела «Развязки»).
    ///
    /// Состояние хранится флагами событий («lore:&lt;id&gt;», прочитанное — «loreseen:&lt;id&gt;») и сохраняется вместе с ними.
    /// </summary>
    public static class Lore
    {
        public const int ShardTotal = 7;
        public const string ChainName = "Великое Молчание";

        public static event Action<LoreEntry> OnUnlocked;

        private static List<LoreEntry> s_all;
        public static IReadOnlyList<LoreEntry> All => s_all ??= Build();

        private static List<string> Flags => AnomalyEventSystem.Instance?.CaptureState()?.Fired;
        private static bool Has(string f) { var l = Flags; return l != null && l.Contains(f); }

        public static LoreEntry Get(string id)
        {
            foreach (var e in All) if (e.Id == id) return e;
            return null;
        }

        public static bool IsUnlocked(string id) => IsUnlocked(Get(id));

        public static bool IsUnlocked(LoreEntry e)
        {
            if (e == null) return false;
            if (Has("lore:" + e.Id)) return true;
            if (e.Auto == null) return false;
            try { return e.Auto(); } catch { return false; }
        }

        /// <summary>Открыть запись. Возвращает true, если она открыта впервые.</summary>
        public static bool Unlock(string id, bool notify = true)
        {
            var e = Get(id);
            var l = Flags;
            if (e == null || l == null || l.Contains("lore:" + id)) return false;
            bool wasAuto = IsUnlocked(e);
            l.Add("lore:" + id);
            if (wasAuto) return false;
            if (notify)
                NotificationCenter.Show(Loc.T("Архив пополнен"), Loc.F("«{0}» — запись в Архиве (клавиша Y)", e.Title), NotificationCenter.Kind.Info, 6f);
            OnUnlocked?.Invoke(e);
            return true;
        }

        public static bool IsSeen(LoreEntry e) => e != null && Has("loreseen:" + e.Id);

        public static void MarkSeen(LoreEntry e)
        {
            var l = Flags;
            if (e == null || l == null || l.Contains("loreseen:" + e.Id)) return;
            l.Add("loreseen:" + e.Id);
        }

        /// <summary>Открытые, но ещё не прочитанные записи (кружок на кнопке Архива).</summary>
        public static int UnreadCount
        {
            get
            {
                if (Flags == null) return 0;
                int n = 0;
                foreach (var e in All) if (IsUnlocked(e) && !IsSeen(e)) n++;
                return n;
            }
        }

        public static int UnlockedCount
        {
            get { int n = 0; foreach (var e in All) if (IsUnlocked(e)) n++; return n; }
        }

        // ==================== ОСКОЛКИ ЛЕТОПИСИ ====================

        public static int ShardCount
        {
            get { int n = 0; foreach (var e in All) if (e.Shard > 0 && IsUnlocked(e)) n++; return n; }
        }

        public static bool ChronicleComplete => ShardCount >= ShardTotal;

        /// <summary>Какой осколок найдут следующим (они открываются по порядку), null — все собраны.</summary>
        public static LoreEntry PeekNextShard()
        {
            int next = ShardCount + 1;
            foreach (var e in All) if (e.Shard == next) return e;
            return null;
        }

        /// <summary>Найти следующий осколок. Седьмой запускает финальную цепочку «Великое Молчание».</summary>
        public static LoreEntry NextShard(EventContext ctx = null)
        {
            var e = PeekNextShard();
            if (e == null || Flags == null) return null;
            Unlock(e.Id, false);
            int n = ShardCount;
            NotificationCenter.Show(Loc.F("Осколок летописи {0} из {1}", n, ShardTotal),
                Loc.F("«{0}» — запись в Архиве (клавиша Y)", e.Title), NotificationCenter.Kind.Success, 7f);
            if (n >= ShardTotal)
                AnomalyEventSystem.Instance?.Schedule("silence_truth", 60, ctx ?? new EventContext(), Loc.T(ChainName),
                    Loc.T("Летопись Строителей собрана целиком. Лингвисты складывают последние строки — и Пульсар Ирис сбился с ритма."));
            return e;
        }

        /// <summary>Событие показано игроку: открыть связанные записи (вызывает AnomalyEventSystem).</summary>
        public static void OnEventShown(string id)
        {
            if (string.IsNullOrEmpty(id) || Flags == null) return;
            switch (id)
            {
                case "heart_found": Unlock("myst_heart"); break;
                case "heart_answer": Unlock("myst_heart_voice"); NextShard(); break;
                case "precursor_signal": Unlock("myst_precursor"); break;
                case "precursor_vault": Unlock("myst_guardians"); break;
                case "precursor_core": NextShard(); break;
                case "leviathan_slain": Unlock("myst_guardians"); NextShard(); break;
                case "ark_signal": Unlock("myst_ark"); break;
                case "mind_awake": Unlock("myst_mind"); break;
                case "brood_found": Unlock("myst_brood"); break;
                case "pirate_haven": Unlock("myst_pirates"); break;
            }
        }

