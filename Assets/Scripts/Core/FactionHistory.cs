        public static FactionHistoryEntry For(FactionInfo f) => ForKey(FactionRegistry.KeyOf(f));

        public static FactionHistoryEntry ForKey(string key)
        {
            if (string.IsNullOrEmpty(key)) return null;
            foreach (var e in All) if (e.Key == key) return e;
            return null;
        }

        /// <summary>Голос фразы (null — нет озвучки: английская версия или файл не собран).</summary>
        public static AudioClip Voice(string key, int chapter, int line)
        {
            if (Loc.English) return null;
            string c = chapter < 0 ? "f" : chapter.ToString();
            return Resources.Load<AudioClip>($"{VoicePath}{key}_{c}_{line}");
        }

        private static HistoryChapter C(string title, string date, string art, params string[] lines)
