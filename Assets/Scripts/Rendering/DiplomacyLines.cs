        public static string Get(LeaderPortraits.Entry leader, Kind kind)
        {
            var table = leader == LeaderPortraits.Xarn ? Xarn
                      : leader == LeaderPortraits.Aquila ? Aquila
                      : leader == LeaderPortraits.Iridia ? Iridia
                      : Astrea;
            var lines = table[(int)kind];
            return lines[Random.Range(0, lines.Length)];
        }

        /// <summary>Приветствие по текущему состоянию отношений.</summary>
        public static Kind GreetingFor(AIEmpireManager ai)
        {
            if (ai.AtWar) return Kind.AtWar;
            if (ai.Opinion >= 25f || ai.HasPact) return Kind.GreetFriendly;
            if (ai.Opinion <= -25f) return Kind.GreetHostile;
            return Kind.GreetNeutral;
        }

        /// <summary>Реплика к предложению ИИ.</summary>
        public static Kind OfferLine(AIEmpireManager.OfferKind k, Deal d) => k switch
        {
            AIEmpireManager.OfferKind.Peace => Kind.OfferPeace,
            AIEmpireManager.OfferKind.Pact => Kind.OfferPact,
            AIEmpireManager.OfferKind.Demand => Kind.Demand,
            _ => d != null && d.FromAI.Count == 0 && d.FromPlayer.Count == 0 ? Kind.OfferTreaty : Kind.OfferTrade
        };
