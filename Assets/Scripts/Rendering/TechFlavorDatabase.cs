        /// <summary>Получить флавор-описание технологии по её Id. Если нет — заглушка.</summary>
        public static string Get(string techId)
        {
            if (string.IsNullOrEmpty(techId)) return GetFallback();
            if (_flavor.TryGetValue(techId, out var text) && !string.IsNullOrEmpty(text))
                return text;
            return GetFallback();
        }

        /// <summary>Есть ли у технологии собственное атмосферное описание.</summary>
        public static bool Has(string techId)
        {
            return !string.IsNullOrEmpty(techId) && _flavor.ContainsKey(techId);
        }

        private static string GetFallback()
            => "Данные по этой технологии засекречены. Разведывательный отдел не предоставил " +
               "детальный отчёт — известно только, что она даёт определённые тактические преимущества.";
    }
